"""Inner loop agent execution runtime managing conversation, tool calls, and limits."""

from __future__ import annotations

import time
import uuid
from typing import TYPE_CHECKING, Any
from uuid import uuid4

from pydantic import BaseModel, Field, ValidationError

from lekka_ai.harness.untrusted import (
    UNTRUSTED_DATA_SYSTEM_PROMPT,
    wrap_tool_output,
)
from lekka_ai.llm.base import Message
from lekka_ai.logging import get_logger
from lekka_ai.schemas.submit import SubmitAnswer
from lekka_ai.tools.submit import SubmitAnswerTool

if TYPE_CHECKING:
    from sqlalchemy.orm import Session

    from lekka_ai.harness.models import AgentTask, Limits
    from lekka_ai.harness.permissions import AgentProfile, ToolView
    from lekka_ai.llm.base import LLMClient

logger = get_logger(__name__)


class AgentRunResult(BaseModel):
    """Execution output and telemetry from an agent runtime cycle."""

    task_id: str = Field(..., description="ID of the assigned task")
    agent_type: str = Field(..., description="Role profile of the executing agent")
    status: str = Field(
        ...,
        description=(
            "Outcome status ('completed', 'partial', 'max_iterations', 'failed')"
        ),
    )
    final_text: str | None = Field(
        default=None,
        description="Plain text final response generated by the LLM",
    )
    messages: list[Message] = Field(
        default_factory=list,
        description="Full dialogue history including instructions, tools, and replies",
    )
    iterations: int = Field(default=0, ge=0, description="Number of LLM turns executed")
    tokens_in: int = Field(default=0, ge=0, description="Total prompt tokens consumed")
    tokens_out: int = Field(
        default=0, ge=0, description="Total completion tokens generated"
    )
    tool_calls_count: int = Field(
        default=0, ge=0, description="Total tool invocations performed"
    )
    limits_hit: list[str] = Field(
        default_factory=list,
        description="List of limit names reached during execution",
    )
    agent_run_id: str | None = Field(
        default=None,
        description="Identifier of the persisted or recorded agent run cycle",
    )
    submission: SubmitAnswer | None = Field(
        default=None,
        description="Final validated SubmitAnswer payload if submitted",
    )
    repair_attempts: int = Field(
        default=0,
        ge=0,
        description="Number of submit_answer validation repair attempts",
    )


class AgentRuntime:
    """Orchestrates single-agent inner loop execution with permissions and tracing."""

    def __init__(self, session: Session | None = None) -> None:
        self.session = session

    @classmethod
    async def run(
        cls,
        task: AgentTask,
        profile: AgentProfile,
        llm: LLMClient,
        tool_view: ToolView,
        limits: Limits | None = None,
        *,
        max_repair_attempts: int = 3,
        session: Session | None = None,
    ) -> AgentRunResult:
        """Execute an agent task through the runtime loop."""
        runtime = cls(session=session)
        return await runtime.execute(
            task,
            profile,
            llm,
            tool_view,
            limits,
            max_repair_attempts=max_repair_attempts,
        )

    async def execute(
        self,
        task: AgentTask,
        profile: AgentProfile,
        llm: LLMClient,
        tool_view: ToolView,
        limits: Limits | None = None,
        *,
        max_repair_attempts: int = 3,
    ) -> AgentRunResult:
        """Run inner loop: build prompt, call LLM, invoke tools, and log run row."""
        # Ensure built-in submit_answer tool is registered
        if "submit_answer" not in tool_view.registry._tools:
            tool_view.registry.register(SubmitAnswerTool(), overwrite=True)

        system_prompt, messages = self._build_initial_messages(task, profile)
        allowed_specs = tool_view.specs()

        max_iterations = (
            limits.max_iterations
            if limits and limits.max_iterations is not None
            else 10
        )
        max_tokens = limits.max_tokens if limits else None
        effective_max_repairs = (
            limits.max_repair_attempts
            if (
                limits is not None
                and hasattr(limits, "max_repair_attempts")
                and limits.max_repair_attempts is not None
            )
            else max_repair_attempts
        )

        # Setup agent_run database tracking if session is available
        agent_run_uuid, db_agent_run = self._initialize_db_agent_run(task)
        if agent_run_uuid:
            tool_view.agent_run_id = agent_run_uuid

        run_id_str = (
            str(agent_run_uuid) if agent_run_uuid else f"agent_run_{uuid4().hex[:10]}"
        )

        iteration = 0
        tokens_in = 0
        tokens_out = 0
        tool_calls_count = 0
        repair_attempts = 0
        limits_hit: list[str] = []
        final_text: str | None = None
        status = "running"
        submitted_answer: SubmitAnswer | None = None
        start_time = time.perf_counter()

        logger.info(
            "Starting agent runtime loop",
            task_id=task.task_id,
            agent_type=profile.agent_type,
            max_iterations=max_iterations,
        )

        while iteration < max_iterations:
            iteration += 1

            # Check execution time limit if configured
            if limits and limits.max_seconds is not None:
                elapsed = time.perf_counter() - start_time
                if elapsed >= limits.max_seconds:
                    limits_hit.append("max_seconds")
                    status = "max_iterations"
                    break

            # Check token limit if configured
            if max_tokens is not None and (tokens_in + tokens_out) >= max_tokens:
                limits_hit.append("max_tokens")
                status = "max_iterations"
                break

            # 1. Call LLM with current dialogue and authorized tool specs
            response = await llm.generate(
                messages=messages,
                tools=allowed_specs if allowed_specs else None,
                system=system_prompt,
            )

            tokens_in += response.usage.input_tokens
            tokens_out += response.usage.output_tokens

            # 2. Check if model returned plain text without tool calls
            if not response.tool_calls:
                final_text = response.text or ""
                messages.append(Message(role="assistant", content=final_text))
                status = "completed"
                break

            # 3. Model returned tool calls - process them through ToolView
            assistant_content = response.text or ""
            messages.append(Message(role="assistant", content=assistant_content))

            loop_should_end = False
            for tc in response.tool_calls:
                tool_calls_count += 1

                # Built-in submit_answer gate interception
                if tc.name == "submit_answer":
                    try:
                        if isinstance(tc.args, SubmitAnswer):
                            submission = tc.args
                        else:
                            submission = SubmitAnswer.model_validate(tc.args)

                        tool_output = await tool_view.execute(tc.name, submission)
                        formatted_output = wrap_tool_output(tc.name, tool_output)
                        messages.append(
                            Message(
                                role="tool",
                                content=formatted_output,
                            )
                        )
                        submitted_answer = submission
                        status = (
                            submission.status.value
                            if hasattr(submission.status, "value")
                            else str(submission.status)
                        )
                        final_text = submission.confidence_rationale
                        loop_should_end = True
                        break
                    except (ValidationError, ValueError) as exc:
                        repair_attempts += 1
                        err_msg = str(exc)

                        # Record failed attempt span in tracer
                        async with tool_view.tracer.span(
                            tc.name,
                            span_type="tool",
                            tool_name=tc.name,
                            agent_run_id=tool_view.agent_run_id,
                            input_json=tc.args if isinstance(tc.args, dict) else {},
                        ) as err_span:
                            err_span.status = "error"
                            err_span.error = err_msg

                        if repair_attempts >= effective_max_repairs:
                            status = "partial"
                            limits_hit.append("submit_validation_failed")
                            obs_msg = (
                                f"Validation failed for submit_answer "
                                f"({repair_attempts}/{effective_max_repairs}):\n"
                                f"{err_msg}\n"
                                "Maximum repair attempts exceeded. Ending task."
                            )
                            messages.append(
                                Message(
                                    role="tool",
                                    content=wrap_tool_output(
                                        tc.name,
                                        {"error": obs_msg, "status": "partial"},
                                    ),
                                )
                            )
                            loop_should_end = True
                            break
                        else:
                            obs_msg = (
                                f"Validation failed for submit_answer "
                                f"({repair_attempts}/{effective_max_repairs}):\n"
                                f"{err_msg}\n"
                                "Please repair the errors and call submit_answer again."
                            )
                            messages.append(
                                Message(
                                    role="tool",
                                    content=wrap_tool_output(
                                        tc.name,
                                        {
                                            "error": obs_msg,
                                            "repair_attempt": repair_attempts,
                                        },
                                    ),
                                )
                            )
                            break

                try:
                    tool_output = await tool_view.execute(tc.name, tc.args)
                except Exception as exc:
                    logger.warning(
                        "Tool execution error in runtime",
                        tool_name=tc.name,
                        error=str(exc),
                    )
                    tool_output = {"error": str(exc)}

                # Delimit and wrap external tool outputs
                formatted_output = wrap_tool_output(tc.name, tool_output)
                messages.append(
                    Message(
                        role="tool",
                        content=formatted_output,
                    )
                )

            if loop_should_end:
                break

            # Check tool call limit if configured
            if (
                limits
                and limits.max_tool_calls is not None
                and tool_calls_count >= limits.max_tool_calls
            ):
                limits_hit.append("max_tool_calls")
                status = "max_iterations"
                break

        if iteration >= max_iterations and status == "running":
            status = "max_iterations"
            limits_hit.append("max_iterations")

        # Update and persist agent_runs row
        self._finalize_db_agent_run(
            db_agent_run=db_agent_run,
            iterations=iteration,
            tokens_in=tokens_in,
            tokens_out=tokens_out,
            status=status,
            limits_hit=limits_hit,
        )

        logger.info(
            "Agent runtime loop concluded",
            task_id=task.task_id,
            agent_type=profile.agent_type,
            status=status,
            iterations=iteration,
            tool_calls_count=tool_calls_count,
            tokens_in=tokens_in,
            tokens_out=tokens_out,
        )

        return AgentRunResult(
            task_id=task.task_id,
            agent_type=profile.agent_type,
            status=status,
            final_text=final_text,
            messages=messages,
            iterations=iteration,
            tokens_in=tokens_in,
            tokens_out=tokens_out,
            tool_calls_count=tool_calls_count,
            limits_hit=limits_hit,
            agent_run_id=run_id_str,
            submission=submitted_answer,
            repair_attempts=repair_attempts,
        )

    def _build_initial_messages(
        self,
        task: AgentTask,
        profile: AgentProfile,
    ) -> tuple[str, list[Message]]:
        """Construct the system prompt and starting dialogue messages."""
        system_parts: list[str] = []
        custom_prompt = profile.load_system_prompt()
        if custom_prompt:
            system_parts.append(custom_prompt.strip())
        else:
            system_parts.append(
                f"You are a specialized financial {profile.agent_type} agent."
            )

        system_parts.append(UNTRUSTED_DATA_SYSTEM_PROMPT)

        if task.as_of_date:
            system_parts.append(
                f"Point-in-time cutoff date: {task.as_of_date}. "
                "Do not reference or assume knowledge after this date."
            )

        system_prompt = "\n\n".join(system_parts)

        user_content_parts = [task.instruction.strip()]
        if task.context_facts:
            facts = "\n".join(
                f"- {f.text if hasattr(f, 'text') else str(f)}"
                for f in task.context_facts
            )
            user_content_parts.append(f"\nContext facts:\n{facts}")

        starting_messages = [
            Message(role="user", content="\n".join(user_content_parts))
        ]
        return system_prompt, starting_messages

    def _initialize_db_agent_run(
        self,
        task: AgentTask,
    ) -> tuple[uuid.UUID | None, Any]:
        """Create an initial agent_runs row in the database if session is present."""
        if not self.session:
            return None, None

        from lekka_ai.db.repository import create_agent_run

        try:
            task_uuid = uuid.UUID(str(task.task_id))
            db_run = create_agent_run(
                self.session,
                task_id=task_uuid,
                iterations=0,
                tokens_in=0,
                tokens_out=0,
                status="running",
            )
            return db_run.id, db_run
        except Exception as exc:
            logger.debug(
                "Skipping DB agent_runs record initialization",
                reason=str(exc),
            )
            return None, None

    def _finalize_db_agent_run(
        self,
        *,
        db_agent_run: Any,
        iterations: int,
        tokens_in: int,
        tokens_out: int,
        status: str,
        limits_hit: list[str],
    ) -> None:
        """Update and commit the completed agent_runs row."""
        if not self.session or db_agent_run is None:
            return

        try:
            db_agent_run.iterations = iterations
            db_agent_run.tokens_in = tokens_in
            db_agent_run.tokens_out = tokens_out
            db_agent_run.status = status
            db_agent_run.limits_hit = limits_hit
            self.session.commit()
            self.session.refresh(db_agent_run)
        except Exception as exc:
            logger.warning(
                "Failed to commit final agent_runs record",
                error=str(exc),
            )
