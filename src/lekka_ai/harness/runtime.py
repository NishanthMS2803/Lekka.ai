logger = get_logger(__name__)


class AgentRunResult(BaseModel):
    """Execution output and telemetry from an agent runtime cycle."""

    task_id: str = Field(..., description="ID of the assigned task")
    agent_type: str = Field(..., description="Role profile of the executing agent")
    status: str = Field(
        ...,
        description=(
            "Outcome status ('completed', 'partial', 'max_iterations', 'failed')"
        ),
    )
    final_text: str | None = Field(
        default=None,
        description="Plain text final response generated by the LLM",
    )
    messages: list[Message] = Field(
        default_factory=list,
        description="Full dialogue history including instructions, tools, and replies",
    )
    iterations: int = Field(default=0, ge=0, description="Number of LLM turns executed")
    tokens_in: int = Field(default=0, ge=0, description="Total prompt tokens consumed")
    tokens_out: int = Field(
        default=0, ge=0, description="Total completion tokens generated"
    )
    tool_calls_count: int = Field(
        default=0, ge=0, description="Total tool invocations performed"
    )
    limits_hit: list[str] = Field(
        default_factory=list,
        description="List of limit names reached during execution",
    )
    agent_run_id: str | None = Field(
        default=None,
        description="Identifier of the persisted or recorded agent run cycle",
    )
    submission: SubmitAnswer | None = Field(
        default=None,
        description="Final validated SubmitAnswer payload if submitted",
    )
    repair_attempts: int = Field(
        default=0,
        ge=0,
        description="Number of submit_answer validation repair attempts",
    )
    stored_claims: list[Any] = Field(
        default_factory=list,
        description="Validated claims persisted into the ledger",
    )


class AgentRuntime:
    """Orchestrates single-agent inner loop execution with permissions and tracing."""

    def __init__(
        self,
        session: Session | None = None,
        ledger: LedgerRepository | None = None,
    ) -> None:
        self.session = session
        self.ledger = ledger

    @classmethod
    async def run(
        cls,
        task: AgentTask,
        profile: AgentProfile,
        llm: LLMClient,
        tool_view: ToolView,
        limits: Limits | None = None,
        *,
        max_repair_attempts: int = 3,
        session: Session | None = None,
        ledger: LedgerRepository | None = None,
        repeat_threshold: int = 3,
    ) -> AgentRunResult:
        """Execute an agent task through the runtime loop."""
        runtime = cls(session=session, ledger=ledger)
        return await runtime.execute(
            task,
            profile,
            llm,
            tool_view,
            limits,
            max_repair_attempts=max_repair_attempts,
            repeat_threshold=repeat_threshold,
        )

    async def execute(
        self,
        task: AgentTask,
        profile: AgentProfile,
        llm: LLMClient,
        tool_view: ToolView,
        limits: Limits | None = None,
        *,
        max_repair_attempts: int = 3,
        repeat_threshold: int = 3,
    ) -> AgentRunResult:
        """Run inner loop: build prompt, call LLM, invoke tools, and log run row."""
        # Ensure built-in submit_answer tool is registered
        if "submit_answer" not in tool_view.registry._tools:
            tool_view.registry.register(SubmitAnswerTool(), overwrite=True)

        system_prompt, messages = self._build_initial_messages(task, profile)
        allowed_specs = tool_view.specs()

        max_iterations = (
            limits.max_iterations
            if limits and limits.max_iterations is not None
            else 10
        )
        max_tokens = limits.max_tokens if limits else None
        effective_max_repairs = (
            limits.max_repair_attempts
            if (
                limits is not None
                and hasattr(limits, "max_repair_attempts")
                and limits.max_repair_attempts is not None
            )
            else max_repair_attempts
        )

        # Setup agent_run database tracking if session is available
        agent_run_uuid, db_agent_run = self._initialize_db_agent_run(task)
        if agent_run_uuid:
            tool_view.agent_run_id = agent_run_uuid

        run_id_str = (
            str(agent_run_uuid) if agent_run_uuid else f"agent_run_{uuid4().hex[:10]}"
        )

        iteration = 0
        tokens_in = 0
        tokens_out = 0
        tool_calls_count = 0
        repair_attempts = 0
        tool_call_counts: dict[tuple[str, str], int] = {}
        limits_hit: list[str] = []
        final_text: str | None = None
        status = "running"
        submitted_answer: SubmitAnswer | None = None
        stored_claims: list[Any] = []
        executed_tool_call_ids: set[str] = set()
        tool_call_id_map: dict[str, uuid.UUID] = {}
        start_time = time.perf_counter()

        # Seed any tool call IDs already linked to agent_run
        if db_agent_run is not None and hasattr(db_agent_run, "tool_calls"):
            for db_tc in db_agent_run.tool_calls:
                executed_tool_call_ids.add(str(db_tc.id))

        logger.info(
            "Starting agent runtime loop",
            task_id=task.task_id,
            agent_type=profile.agent_type,
            max_iterations=max_iterations,
        )

        breached_limit: str | None = None

        while iteration < max_iterations:
            # Check execution time limit if configured
            if limits and limits.max_seconds is not None:
                elapsed = time.perf_counter() - start_time
                if elapsed >= limits.max_seconds:
                    breached_limit = "max_seconds"
                    break

            # Check token limit if configured
            if max_tokens is not None and (tokens_in + tokens_out) >= max_tokens:
                breached_limit = "max_tokens"
                break

            # Check tool call limit if configured
            if (
                limits
                and limits.max_tool_calls is not None
                and tool_calls_count >= limits.max_tool_calls
            ):
                breached_limit = "max_tool_calls"
                break

            iteration += 1

            # 1. Call LLM with current dialogue and authorized tool specs
            response = await llm.generate(
                messages=messages,
                tools=allowed_specs if allowed_specs else None,
                system=system_prompt,
            )

            tokens_in += response.usage.input_tokens
            tokens_out += response.usage.output_tokens

            # Check token limit immediately after generation if configured
            if max_tokens is not None and (tokens_in + tokens_out) >= max_tokens:
                has_submit = any(
                    tc.name == "submit_answer" for tc in response.tool_calls
                )
                if not has_submit:
                    breached_limit = "max_tokens"
                    break

            # 2. Check if model returned plain text without tool calls
            if not response.tool_calls:
                final_text = response.text or ""
                messages.append(Message(role="assistant", content=final_text))
                status = "completed"
                break

            # 3. Model returned tool calls - process them through ToolView
            assistant_content = response.text or ""
            messages.append(Message(role="assistant", content=assistant_content))

            loop_should_end = False
            for tc in response.tool_calls:
                tool_calls_count += 1

                # Built-in submit_answer gate interception
                if tc.name == "submit_answer":
                    try:
                        if isinstance(tc.args, SubmitAnswer):
                            submission = tc.args
                        else:
                            submission = SubmitAnswer.model_validate(tc.args)

                        # Citation integrity & point-in-time date validation
                        citation_errors = self._validate_citation_integrity(
                            submission=submission,
                            task=task,
                            executed_tool_call_ids=executed_tool_call_ids,
                        )
                        if citation_errors:
                            msg = (
                                "Citation integrity verification failed:\n"
                                + "\n".join(f"- {e}" for e in citation_errors)
                            )
                            raise ValueError(msg)

                        tool_output = await tool_view.execute(tc.name, submission)
                        formatted_output = wrap_tool_output(tc.name, tool_output)
                        messages.append(
                            Message(
                                role="tool",
                                content=formatted_output,
                            )
                        )

                        # Write valid claims to the ledger
                        stored_claims = self._write_claims_to_ledger(
                            submission=submission,
                            task=task,
                            db_agent_run=db_agent_run,
                            tool_call_id_map=tool_call_id_map,
                        )

                        submitted_answer = submission
                        status = (
                            submission.status.value
                            if hasattr(submission.status, "value")
                            else str(submission.status)
                        )
                        final_text = submission.confidence_rationale
                        loop_should_end = True
                        break
                    except (ValidationError, ValueError) as exc:
                        repair_attempts += 1
                        err_msg = str(exc)

                        # Record failed attempt span in tracer
                        async with tool_view.tracer.span(
                            tc.name,
                            span_type="tool",
                            tool_name=tc.name,
                            agent_run_id=tool_view.agent_run_id,
                            input_json=tc.args if isinstance(tc.args, dict) else {},
                        ) as err_span:
                            err_span.status = "error"
                            err_span.error = err_msg

                        if repair_attempts >= effective_max_repairs:
                            status = "partial"
                            limits_hit.append("submit_validation_failed")
                            obs_msg = (
                                f"Validation failed for submit_answer "
                                f"({repair_attempts}/{effective_max_repairs}):\n"
                                f"{err_msg}\n"
                                "Maximum repair attempts exceeded. Ending task."
                            )
                            messages.append(
                                Message(
                                    role="tool",
                                    content=wrap_tool_output(
                                        tc.name,
                                        {"error": obs_msg, "status": "partial"},
                                    ),
                                )
                            )
                            loop_should_end = True
                            break
                        else:
                            obs_msg = (
                                f"Validation failed for submit_answer "
                                f"({repair_attempts}/{effective_max_repairs}):\n"
                                f"{err_msg}\n"
                                "Please repair the errors and call submit_answer again."
                            )
                            messages.append(
                                Message(
                                    role="tool",
                                    content=wrap_tool_output(
                                        tc.name,
                                        {
                                            "error": obs_msg,
                                            "repair_attempt": repair_attempts,
                                        },
                                    ),
                                )
                            )
                            break

                # Repeat detection: same tool + same args, 3rd time
                call_key = (tc.name, canonicalize_tool_args(tc.args))
                tool_call_counts[call_key] = tool_call_counts.get(call_key, 0) + 1
                if tool_call_counts[call_key] >= repeat_threshold:
                    interruption_msg = (
                        f"Repeated identical tool call detected: tool '{tc.name}' "
                        f"has been called {tool_call_counts[call_key]} times with "
                        "identical arguments. You must change your approach or "
                        "adjust your parameters."
                    )
                    logger.warning(
                        "Repeated identical tool call interrupted",
                        tool_name=tc.name,
                        repeat_count=tool_call_counts[call_key],
                    )
                    tool_output = {
                        "error": True,
                        "error_type": "RepeatedToolCallError",
                        "message": interruption_msg,
                        "retryable": False,
                    }
                    async with tool_view.tracer.span(
                        tc.name,
                        span_type="tool",
                        tool_name=tc.name,
                        agent_run_id=tool_view.agent_run_id,
                        input_json=tc.args if isinstance(tc.args, dict) else {},
                    ) as rep_span:
                        rep_span.status = "error"
                        rep_span.error = interruption_msg
                        rep_span.output_json = tool_output

                    formatted_output = wrap_tool_output(tc.name, tool_output)
                    messages.append(
                        Message(
                            role="tool",
                            content=formatted_output,
                        )
                    )
                    continue

                try:
                    tool_output = await tool_view.execute(tc.name, tc.args)
                    executed_tool_call_ids.add(str(tc.id).strip())
                    if tool_view.tracer.spans:
                        latest_span = tool_view.tracer.spans[-1]
                        executed_tool_call_ids.add(str(latest_span.id))
                        if latest_span.tool_call_id:
                            executed_tool_call_ids.add(str(latest_span.tool_call_id))
                            tool_call_id_map[str(tc.id).strip()] = (
                                latest_span.tool_call_id
                            )
                except Exception as exc:
                    is_retryable = is_retryable_tool_error(exc)
                    logger.warning(
                        "Tool execution error in runtime",
                        tool_name=tc.name,
                        error=str(exc),
                        retryable=is_retryable,
                    )
                    tool_output = {
                        "error": True,
                        "error_type": type(exc).__name__,
                        "message": str(exc),
                        "retryable": is_retryable,
                    }

                # Delimit and wrap external tool outputs
                formatted_output = wrap_tool_output(tc.name, tool_output)
                messages.append(
                    Message(
                        role="tool",
                        content=formatted_output,
                    )
                )

            if loop_should_end:
                break

            # Check tool call limit if configured
            if (
                limits
                and limits.max_tool_calls is not None
                and tool_calls_count >= limits.max_tool_calls
            ):
                breached_limit = "max_tool_calls"
                break

            # Check execution time limit if configured
            if limits and limits.max_seconds is not None:
                elapsed = time.perf_counter() - start_time
                if elapsed >= limits.max_seconds:
                    breached_limit = "max_seconds"
                    break

            if iteration >= max_iterations:
                breached_limit = "max_iterations"
                break

        if (
            iteration >= max_iterations
            and status == "running"
            and breached_limit is None
            and submitted_answer is None
        ):
            breached_limit = "max_iterations"

        # Handle forced submit when any execution limit was hit
        if (
            breached_limit is not None
            and status == "running"
            and submitted_answer is None
        ):
            if breached_limit not in limits_hit:
                limits_hit.append(breached_limit)

            (
                forced_sub,
                forced_status,
                forced_text,
                forced_stored,
                extra_tc_count,
                extra_tokens_in,
                extra_tokens_out,
            ) = await self._handle_forced_submit(
                breached_limit=breached_limit,
                task=task,
                profile=profile,
                llm=llm,
                tool_view=tool_view,
                messages=messages,
                system_prompt=system_prompt,
                limits_hit=limits_hit,
                executed_tool_call_ids=executed_tool_call_ids,
                tool_call_id_map=tool_call_id_map,
                db_agent_run=db_agent_run,
            )

            iteration += 1
            tokens_in += extra_tokens_in
            tokens_out += extra_tokens_out
            tool_calls_count += extra_tc_count

            if forced_sub is not None:
                submitted_answer = forced_sub
                status = forced_status
                final_text = forced_text
                stored_claims = forced_stored
            else:
                # Hard-stop if agent still doesn't submit
                status = "partial"
                final_text = forced_text or final_text

        # Update and persist agent_runs row
        self._finalize_db_agent_run(
            db_agent_run=db_agent_run,
            iterations=iteration,
            tokens_in=tokens_in,
            tokens_out=tokens_out,
            status=status,
            limits_hit=limits_hit,
        )

        logger.info(
            "Agent runtime loop concluded",
            task_id=task.task_id,
            agent_type=profile.agent_type,
            status=status,
            iterations=iteration,
            tool_calls_count=tool_calls_count,
            tokens_in=tokens_in,
            tokens_out=tokens_out,
        )

        return AgentRunResult(
            task_id=task.task_id,
            agent_type=profile.agent_type,
            status=status,
            final_text=final_text,
            messages=messages,
            iterations=iteration,
            tokens_in=tokens_in,
            tokens_out=tokens_out,
            tool_calls_count=tool_calls_count,
            limits_hit=limits_hit,
            agent_run_id=run_id_str,
            submission=submitted_answer,
            repair_attempts=repair_attempts,
            stored_claims=stored_claims,
        )

    async def _handle_forced_submit(
        self,
        *,
        breached_limit: str,
        task: AgentTask,
        profile: AgentProfile,
        llm: LLMClient,
        tool_view: ToolView,
        messages: list[Message],
        system_prompt: str,
        limits_hit: list[str],
        executed_tool_call_ids: set[str],
        tool_call_id_map: dict[str, uuid.UUID],
        db_agent_run: Any,
    ) -> tuple[SubmitAnswer | None, str, str | None, list[Any], int, int, int]:
        """Send final instruction forcing submit_answer, or hard-stop."""
        final_instruction = (
            f"Execution limit reached ({breached_limit}). You must immediately call "
            "submit_answer with status='partial' or status='insufficient_evidence'."
        )
        messages.append(Message(role="user", content=final_instruction))

        forced_response = await llm.generate(
            messages=messages,
            tools=[tool_view.get("submit_answer").to_spec()],
            system=system_prompt,
        )

        tokens_in = forced_response.usage.input_tokens
        tokens_out = forced_response.usage.output_tokens

        submit_call = next(
            (tc for tc in forced_response.tool_calls if tc.name == "submit_answer"),
            None,
        )

        if submit_call is None:
            # Agent still did not submit -> hard stop
            text_out = forced_response.text or ""
            messages.append(Message(role="assistant", content=text_out))
            return None, "partial", text_out, [], 0, tokens_in, tokens_out

        messages.append(Message(role="assistant", content=forced_response.text or ""))

        try:
            if isinstance(submit_call.args, SubmitAnswer):
                submission = submit_call.args
            elif isinstance(submit_call.args, dict):
                raw_args = dict(submit_call.args)
                raw_st = str(raw_args.get("status", "")).strip().lower()
                if raw_st not in ("partial", "insufficient_evidence"):
                    raw_args["status"] = AnswerStatus.PARTIAL
                submission = SubmitAnswer.model_validate(raw_args)
            else:
                submission = SubmitAnswer.model_validate(submit_call.args)

            # Enforce status is partial or insufficient_evidence
            if submission.status not in (
                AnswerStatus.PARTIAL,
                AnswerStatus.INSUFFICIENT_EVIDENCE,
                "partial",
                "insufficient_evidence",
            ):
                submission.status = AnswerStatus.PARTIAL

            # Lower confidence automatically (cap at 0.5 and halve original)
            orig_conf = float(submission.confidence)
            lowered_conf = round(min(orig_conf * 0.5, 0.5), 2)
            submission.confidence = lowered_conf

            # Set limits_hit on the submission
            for lim in limits_hit:
                if lim not in submission.limits_hit:
                    submission.limits_hit.append(lim)

            # Filter out any claims with citation violations
            valid_claims = []
            for cl in submission.claims:
                single_sub = SubmitAnswer(
                    task_id=submission.task_id,
                    agent_type=submission.agent_type,
                    status=submission.status,
                    claims=[cl],
                    confidence=submission.confidence,
                    confidence_rationale=submission.confidence_rationale,
                )
                errs = self._validate_citation_integrity(
                    submission=single_sub,
                    task=task,
                    executed_tool_call_ids=executed_tool_call_ids,
                )
                if not errs:
                    valid_claims.append(cl)
            submission.claims = valid_claims

            tool_output = await tool_view.execute(submit_call.name, submission)
            messages.append(
                Message(
                    role="tool",
                    content=wrap_tool_output(submit_call.name, tool_output),
                )
            )

            stored = self._write_claims_to_ledger(
                submission=submission,
                task=task,
                db_agent_run=db_agent_run,
                tool_call_id_map=tool_call_id_map,
            )

            status_str = (
                submission.status.value
                if hasattr(submission.status, "value")
                else str(submission.status)
            )
            return (
                submission,
                status_str,
                submission.confidence_rationale,
                stored,
                1,
                tokens_in,
                tokens_out,
            )
        except Exception as exc:
            logger.warning("Forced submit processing failed", error=str(exc))
            return None, "partial", str(exc), [], 1, tokens_in, tokens_out

    @staticmethod
    def _parse_date(val: Any) -> date | None:
        """Parse string, datetime, or date into datetime.date."""
        if val is None:
            return None
        if isinstance(val, datetime):
            return val.date()
        if isinstance(val, date):
            return val
        s = str(val).strip()
        if not s:
            return None
        try:
            return date.fromisoformat(s[:10])
        except Exception:
            return None

    def _validate_citation_integrity(
        self,
        submission: SubmitAnswer,
        task: AgentTask,
        executed_tool_call_ids: set[str],
    ) -> list[str]:
        """Verify cited tool_call_ids were executed and dates obey task cutoff."""
        errors: list[str] = []
        task_date = self._parse_date(task.as_of_date) if task.as_of_date else None

        for claim in submission.claims:
            # Check claim-level as_of_date if specified
            if hasattr(claim, "as_of_date") and getattr(claim, "as_of_date", None):
                c_date = self._parse_date(claim.as_of_date)
                if c_date and task_date and c_date > task_date:
                    errors.append(
                        f"Claim '{claim.claim_id}' cites as_of_date "
                        f"'{claim.as_of_date}' exceeding task cutoff "
                        f"'{task.as_of_date}'"
                    )

            # Check evidence citations
            for ev in claim.evidence:
                if ev.tool_call_id is not None:
                    tid = str(ev.tool_call_id).strip()
                    if tid and tid not in executed_tool_call_ids:
                        errors.append(
                            f"Claim '{claim.claim_id}' cites unexecuted or "
                            f"invented tool_call_id '{ev.tool_call_id}'"
                        )

                if ev.as_of_date is not None and task_date is not None:
                    ev_date = self._parse_date(ev.as_of_date)
                    if ev_date and ev_date > task_date:
                        errors.append(
                            f"Claim '{claim.claim_id}' cites evidence as_of_date "
                            f"'{ev.as_of_date}' exceeding task cutoff "
                            f"'{task.as_of_date}'"
                        )

        return errors

    def _write_claims_to_ledger(
        self,
        submission: SubmitAnswer,
        task: AgentTask,
        db_agent_run: Any,
        tool_call_id_map: dict[str, uuid.UUID],
    ) -> list[Any]:
        """Persist valid submission claims and linked evidence into ledger storage."""
        if not submission.claims:
            return []

        # Map string tool_call_ids to genuine DB tool_call UUIDs if available
        claims_to_store: list[Any] = []
        for claim in submission.claims:
            updated_evidence = []
            for ev in claim.evidence:
                if ev.tool_call_id and str(ev.tool_call_id) in tool_call_id_map:
                    resolved_uuid = tool_call_id_map[str(ev.tool_call_id)]
                    updated_ev = ev.model_copy(
                        update={"tool_call_id": str(resolved_uuid)}
                    )
                    updated_evidence.append(updated_ev)
                else:
                    updated_evidence.append(ev)
            claims_to_store.append(
                claim.model_copy(update={"evidence": updated_evidence})
            )

        if self.session is not None or self.ledger is not None:
            from lekka_ai.db.ledger import LedgerRepository
            from lekka_ai.db.models import Task
            from lekka_ai.db.repository import create_run

            ledger_repo = self.ledger or LedgerRepository(self.session)  # type: ignore[arg-type]

            task_uuid = None
            if db_agent_run is not None and hasattr(db_agent_run, "task_id"):
                task_uuid = db_agent_run.task_id
            else:
                try:
                    task_uuid = uuid.UUID(str(task.task_id))
                except (ValueError, TypeError):
                    task_uuid = None

            if task_uuid is not None and self.session is not None:
                db_task = self.session.query(Task).filter_by(id=task_uuid).first()
                if db_task is None:
                    task_uuid = None

            run_uuid = None
            if hasattr(task, "run_id") and getattr(task, "run_id", None):
                try:
                    run_uuid = uuid.UUID(str(task.run_id))
                except (ValueError, TypeError):
                    pass

            if run_uuid is None and self.session is not None and task_uuid is not None:
                db_task = self.session.query(Task).filter_by(id=task_uuid).first()
                if db_task and db_task.run_id:
                    run_uuid = db_task.run_id

            if run_uuid is None and self.session is not None:
                db_run = create_run(self.session, question=task.instruction)
                run_uuid = db_run.id
            elif run_uuid is None:
                run_uuid = uuid4()

            agent_run_uuid = db_agent_run.id if db_agent_run is not None else None

            persisted = ledger_repo.add_claims(
                claims_to_store,
                run_id=run_uuid,
                task_id=task_uuid,
                agent_run_id=agent_run_uuid,
            )
            if self.session is not None:
                self.session.commit()
            return persisted

        return claims_to_store

    def _build_initial_messages(
        self,
        task: AgentTask,
        profile: AgentProfile,
    ) -> tuple[str, list[Message]]:
        """Construct the system prompt and starting dialogue messages."""
        system_parts: list[str] = []
        custom_prompt = profile.load_system_prompt()
        if custom_prompt:
            system_parts.append(custom_prompt.strip())
        else:
            system_parts.append(
                f"You are a specialized financial {profile.agent_type} agent."
            )

        system_parts.append(UNTRUSTED_DATA_SYSTEM_PROMPT)

        if task.as_of_date:
            system_parts.append(
                f"Point-in-time cutoff date: {task.as_of_date}. "
                "Do not reference or assume knowledge after this date."
            )

        system_prompt = "\n\n".join(system_parts)

        user_content_parts = [task.instruction.strip()]
        if task.context_facts:
            facts = "\n".join(
                f"- {f.text if hasattr(f, 'text') else str(f)}"
                for f in task.context_facts
            )
            user_content_parts.append(f"\nContext facts:\n{facts}")

        starting_messages = [
            Message(role="user", content="\n".join(user_content_parts))
        ]
        return system_prompt, starting_messages

    def _initialize_db_agent_run(
        self,
        task: AgentTask,
    ) -> tuple[uuid.UUID | None, Any]:
        """Create an initial agent_runs row in the database if session is present."""
        if not self.session:
            return None, None

        from lekka_ai.db.repository import create_agent_run

        try:
            task_uuid = uuid.UUID(str(task.task_id))
            db_run = create_agent_run(
                self.session,
                task_id=task_uuid,
                iterations=0,
                tokens_in=0,
                tokens_out=0,
                status="running",
            )
            return db_run.id, db_run
        except Exception as exc:
            logger.debug(
                "Skipping DB agent_runs record initialization",
                reason=str(exc),
            )
            return None, None

    def _finalize_db_agent_run(
        self,
        *,
        db_agent_run: Any,
        iterations: int,
        tokens_in: int,
        tokens_out: int,
        status: str,
        limits_hit: list[str],
    ) -> None:
        """Update and commit the completed agent_runs row."""
        if not self.session or db_agent_run is None:
            return

        try:
            db_agent_run.iterations = iterations
            db_agent_run.tokens_in = tokens_in
            db_agent_run.tokens_out = tokens_out
            db_agent_run.status = status
            db_agent_run.limits_hit = limits_hit
            self.session.commit()
            self.session.refresh(db_agent_run)
        except Exception as exc:
            logger.warning(
                "Failed to commit final agent_runs record",
                error=str(exc),
            )
