class PlanValidationError(ValueError):
    """Base exception for plan validation errors."""


class EmptyPlanError(PlanValidationError):
    """Raised when a plan contains no tasks."""


class UnknownAgentTypeError(PlanValidationError):
    """Raised when a task references an agent type not in available profiles."""


class InvalidDependencyError(PlanValidationError):
    """Raised when task dependencies are invalid or violate wave constraints."""


class GenericInstructionError(PlanValidationError):
    """Raised when a task instruction is too generic (e.g. 'analyze X')."""


class PlannedTaskSpec(BaseModel):
    """Structured task specification generated by parent LLM."""

    model_config = ConfigDict(extra="ignore")

    task_id: str = Field(
        ...,
        description="Unique task slug, e.g. 'task_market_aapl', 'task_news_aapl'",
    )
    agent_type: str = Field(
        ...,
        description="Target specialist agent type matching an available profile",
    )
    instruction: str = Field(
        ...,
        description=(
            "Specific, actionable instruction with explicit metrics and scope. "
            "Never use generic instructions like 'analyze X' or 'analyze AAPL'."
        ),
    )
    depends_on: list[str] = Field(
        default_factory=list,
        description="List of prerequisite task_ids that must complete first",
    )
    priority: int = Field(
        default=1,
        description="Scheduling priority integer (higher executed first)",
    )
    expected_cost: float = Field(
        default=0.0,
        description="Estimated token or dollar budget",
    )


class PlanSpec(BaseModel):
    """Structured plan specification generated by parent LLM."""

    model_config = ConfigDict(extra="ignore")

    tasks: list[PlannedTaskSpec] = Field(
        ...,
        description="Ordered list of planned specialist tasks",
    )


PLANNER_SYSTEM_PROMPT = """\
You are the Lead Investment Research Orchestrator for Lekka AI.
Your job is to decompose a user's financial research query into an optimal,
dependency-aware Execution Plan consisting of specialized sub-agent tasks.


AVAILABLE SPECIALIST PROFILES:
- 'market': Price action, return, volatility, drawdown, beta vs benchmark,
  moving averages, and technical trend regime.
- 'news': Catalysts, earnings releases, 8-K filings, management commentary,
  and sentiment events.
- 'fundamental': 10-K/10-Q accounting statements, revenue growth, margin trends,
  balance sheet leverage, debt service, and consensus estimates.
- 'valuation': Intrinsic DCF modeling, reverse DCF implied growth rates,
  trading multiples, and bear/base/bull scenario tables.
- 'risk': Synthesis of downside risks, stress testing, debt/solvency vulnerabilities,
  and critical review of wave-1 specialist findings.

CORE ROUTING DIRECTIVES:
1. MOVE EXPLANATION ('move_explanation', e.g. "Why did AAPL drop today?"):
   - Plan ONLY 'news' and 'market' specialist agents.
   - DO NOT plan 'valuation' or 'fundamental' agents because intrinsic DCFs and
     long-term accounting filings do not explain short-term intraday or single-day
     price drops.
   - 'news' and 'market' are wave-1 parallel tasks with empty depends_on ([]).

2. INVESTMENT EVALUATION ('investment_evaluation', e.g. "Is AAPL attractive?"):
   - Wave-1 parallel tasks: 'fundamental', 'valuation', and 'news' with depends_on=[].
   - Wave-2 synthesis task: 'risk' specialist, which MUST depend on ALL wave-1 tasks
     ('fundamental', 'valuation', and 'news') to synthesize downside vulnerabilities.

3. SPECIFIC TASK INSTRUCTIONS (CRITICAL):
   - You MUST provide highly detailed, concrete instructions for each specialist.
   - NEVER use generic phrases such as 'analyze AAPL' or 'evaluate stock'.
   - Examples of specific instructions:
     * Market: "Retrieve 1-year daily market data for AAPL as of {as_of_date}. Compute
       volatility, max drawdown, beta vs SPY, and moving average alignment for trend."
     * News: "Search recent SEC 8-K filings and news catalysts for AAPL up to
       {as_of_date} to identify earnings misses, management changes, or macro factors."
     * Fundamental: "Extract reported FY23-FY24 financials for AAPL. Evaluate
       revenue growth, gross and operating margin trajectories, and net debt."
     * Valuation: "Model bear, base, and bull DCF scenarios for AAPL as of {as_of_date}.
       Run reverse DCF at market price to solve for market-implied growth."
     * Risk: "Synthesize findings from fundamental, valuation, and news agents.
       Evaluate downside vulnerabilities, multiple compression, and leverage."

4. DEPENDENCIES & PRIORITIES:
   - Independent data-gathering specialists are Wave 1 (depends_on: [], priority: 2).
   - Synthesis and downstream specialists (e.g. 'risk') are Wave 2
     (depends_on: [wave-1 task_ids], priority: 1).
   - All task_ids referenced in depends_on must exist in the plan.
     Circular dependencies are strictly forbidden.

5. RESTRICTED AGENT TYPES:
   - Only assign tasks to agent types present in the provided available profiles.
"""


def validate_plan(
    plan: Plan,
    allowed_agent_types: Iterable[str] | dict[str, Any],
) -> None:
    """Validate plan constraints: non-empty, known agents, instructions, DAG rules.

    Args:
        plan: The execution Plan to validate.
        allowed_agent_types: Collection or dictionary of permitted agent types.

    Raises:
        EmptyPlanError: If plan has no tasks.
        UnknownAgentTypeError: If any task has an unauthorized agent type.
        GenericInstructionError: If any task instruction is generic like 'analyze X'.
        InvalidDependencyError: If risk agent lacks wave-1 dependencies or DAG invalid.
    """
    # 1. At least one task
    if not plan.tasks:
        raise EmptyPlanError("Plan must contain at least one task.")

    allowed_set = set(allowed_agent_types)

    # 2. Check each task for known agent type and specific instruction
    vague_patterns = {
        "analyze",
        "analyze x",
        "analyze stock",
        "analyze ticker",
        "analyze company",
        "evaluate",
        "evaluate stock",
        "review",
        "check",
    }

    for task in plan.tasks:
        if task.agent_type not in allowed_set:
            raise UnknownAgentTypeError(
                f"Task '{task.task_id}' specifies unknown agent type "
                f"'{task.agent_type}'. Allowed types: {sorted(allowed_set)}"
            )

        clean_instr = task.instruction.strip().lower()
        if clean_instr in vague_patterns or bool(
            re.match(r"^analyze\s+[a-z0-9\.\-]+$", clean_instr)
        ):
            raise GenericInstructionError(
                f"Task '{task.task_id}' has generic instruction '{task.instruction}'. "
                "Instructions must provide specific objectives and metrics."
            )

    # 3. DAG structural validation (dependencies exist, no cycles)
    try:
        plan.validate_dag()
    except Exception as exc:
        raise InvalidDependencyError(f"DAG validation failed: {exc}") from exc

    # 4. Risk agent depends on wave-1 agents
    wave_1_tasks = [
        t for t in plan.tasks if t.agent_type != "risk" and not t.depends_on
    ]
    wave_1_ids = {t.task_id for t in wave_1_tasks}

    for task in plan.tasks:
        if task.agent_type == "risk":
            if not task.depends_on:
                raise InvalidDependencyError(
                    f"Risk agent task '{task.task_id}' must depend on wave-1 agents, "
                    "but has empty depends_on."
                )
            # If wave-1 tasks exist in the plan, risk agent must depend on wave-1 tasks
            if wave_1_ids and not set(task.depends_on).intersection(wave_1_ids):
                raise InvalidDependencyError(
                    f"Risk agent task '{task.task_id}' depends on {task.depends_on}, "
                    f"which does not include any wave-1 tasks: {sorted(wave_1_ids)}."
                )


def _resolve_allowed_agent_types(
    available_profiles: dict[str, AgentProfile] | Iterable[str] | None,
) -> list[str]:
    """Extract list of permitted agent type names."""
    if available_profiles is None:
        try:
            loaded = load_profiles()
            return list(loaded.keys())
        except Exception:
            return ["market", "news", "fundamental", "valuation", "risk", "analyst"]

    if isinstance(available_profiles, dict):
        return list(available_profiles.keys())

    return list(available_profiles)


def _parse_plan_spec(raw_content: Any) -> PlanSpec:
    """Parse raw LLM structured output or text into PlanSpec."""
    if isinstance(raw_content, PlanSpec):
        return raw_content

    if isinstance(raw_content, dict):
        return PlanSpec.model_validate(raw_content)

    if isinstance(raw_content, str):
        clean_text = raw_content.strip()
        fence_match = re.search(r"```(?:json)?\s*([\s\S]*?)\s*```", clean_text)
        if fence_match:
            clean_text = fence_match.group(1).strip()
        data = json.loads(clean_text)
        return PlanSpec.model_validate(data)

    raise ValueError(
        f"Unable to parse PlanSpec from output of type {type(raw_content)}"
    )


async def plan_query(
    query: ParsedQuery,
    available_profiles: dict[str, AgentProfile] | Iterable[str] | None = None,
    llm: LLMClient | None = None,
    *,
    validate: bool = True,
) -> Plan:
    """Generate a validated Plan for a user query using the parent LLM.

    Args:
        query: ParsedQuery object with intent, tickers, horizon, and dates.
        available_profiles: Permitted agent profiles or agent type names.
        llm: Optional LLM client (defaults to GeminiClient).
        validate: When True, runs validate_plan to enforce DAG and wave constraints.

    Returns:
        A validated Plan instance containing PlannedTask items.

    Raises:
        PlanValidationError: If plan generation produces invalid tasks or dependencies.
    """
    allowed_types = _resolve_allowed_agent_types(available_profiles)

    # 1. Initialize LLM if not provided
    if llm is None:
        settings = get_settings()
        llm = GeminiClient(
            api_key=settings.GEMINI_API_KEY,
            model=settings.GEMINI_MODEL,
        )

    # 2. Build user prompt
    tickers_str = ", ".join(query.tickers) if query.tickers else "None specified"
    intent_val = (
        query.intent.value
        if isinstance(query.intent, QueryIntent)
        else str(query.intent)
    )
    user_prompt = (
        f"PARSED QUERY:\n"
        f"- Intent: {intent_val}\n"
        f"- Tickers: {tickers_str}\n"
        f"- Horizon: {query.horizon or 'Unspecified'}\n"
        f"- Risk Focus: {query.risk_focus or 'General'}\n"
        f"- As Of Date: {query.as_of_date}\n"
        f"- Needs Clarification: {query.needs_clarification}\n\n"
        f"ALLOWED AGENT TYPES FOR THIS PLAN: {allowed_types}\n\n"
        f"Create an execution plan with specific task instructions and dependencies."
    )

    # 3. Call LLM for structured plan
    response = await llm.generate(
        messages=[Message(role="user", content=user_prompt)],
        response_schema=PlanSpec,
        system=PLANNER_SYSTEM_PROMPT,
    )

    # 4. Extract and convert PlanSpec
    plan_spec: PlanSpec
    if response.structured_output is not None:
        plan_spec = _parse_plan_spec(response.structured_output)
    elif response.text:
        plan_spec = _parse_plan_spec(response.text)
    else:
        raise EmptyPlanError("LLM returned an empty response with no tasks planned.")

    # 5. Convert PlanSpec to Plan
    plan = Plan()
    for spec in plan_spec.tasks:
        plan.add_task(
            PlannedTask(
                task_id=spec.task_id,
                agent_type=spec.agent_type,
                instruction=spec.instruction,
                depends_on=spec.depends_on,
                priority=spec.priority,
                expected_cost=spec.expected_cost,
            )
        )

    # 6. Validate plan constraints
    if validate:
        validate_plan(plan, allowed_agent_types=allowed_types)

    return plan


create_plan = plan_query
